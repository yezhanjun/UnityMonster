"""Synchronize Unity-exported dependencies while preserving existing GUID paths.

Run with UnityMonster closed. Source list is generated by AssetDatabase.GetDependencies.
Usage: python Tools/SyncVrcCharacters.py SOURCE_PROJECT DEPENDENCY_LIST
"""
from pathlib import Path
import sys, re, hashlib, json, shutil

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]).resolve()
paths = Path(sys.argv[2]).read_text(encoding='utf-8-sig').splitlines()
def guid(p):
    m = re.search(r'^guid: ([0-9a-f]{32})', p.read_text(encoding='utf-8-sig'), re.M)
    return m[1] if m else None
index = {}
for base in ['Assets', 'Packages']:
    for meta in (root/base).rglob('*.meta'):
        g = guid(meta)
        if g:
            if g in index: raise RuntimeError('Duplicate target GUID: '+g)
            index[g] = Path(str(meta)[:-5])
# Only ship referenced scripts and their code-only runtime dependencies, not preview UI.
referenced = set()
for rel in paths:
    p = source/rel
    if p.suffix.lower() in {'.prefab','.asset','.mat','.controller','.anim'}:
        referenced.update(re.findall(rb'guid: ([0-9a-f]{32})',p.read_bytes()))
required = {'WardrobeBinding.cs','IBoneSimulationOwnership.cs','WendyExpressionChinese.cs'}
report = []
backup = root/'Logs/VrcSync20261117/backup'
for rel in paths:
    src = source/rel
    if not src.is_file(): continue
    meta = Path(str(src)+'.meta')
    if not meta.exists(): raise RuntimeError('No metadata: '+rel)
    g = guid(meta)
    if src.suffix == '.cs' and g.encode() not in referenced and src.name not in required:
        if g not in index: continue
    dst = index.get(g,root/'Assets/VRC'/Path(rel).relative_to('Assets'))
    if not dst.resolve().is_relative_to((root/'Assets/VRC').resolve()):
        report.append({'source':rel,'target':dst.relative_to(root).as_posix(),'guid':g,'action':'reuse-shared'})
        continue
    if dst.exists() and guid(Path(str(dst)+'.meta')) != g: raise RuntimeError('Path collision: '+str(dst))
    incoming = src.read_bytes()
    previous = dst.read_bytes() if dst.exists() else None
    # Unity text serialization can differ only by CRLF/LF; preserve target convention.
    if previous is not None and b'\0' not in incoming[:4096]:
        if b'\r\n' in previous:
            incoming = incoming.replace(b'\r\n',b'\n').replace(b'\n',b'\r\n')
    changed = previous != incoming
    if changed:
        if dst.exists():
            save=backup/dst.relative_to(root);save.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(dst,save)
        dst.parent.mkdir(parents=True,exist_ok=True)
        dst.write_bytes(incoming)
        if not Path(str(dst)+'.meta').exists(): shutil.copy2(meta,Path(str(dst)+'.meta'))
    report.append({'source':rel,'target':dst.relative_to(root).as_posix(),'guid':g,'action':'sync' if changed else 'unchanged','sha256':hashlib.sha256(src.read_bytes()).hexdigest()})
out=root/'Docs/Resources/VRC角色同步清单-20261117.json'
out.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'assets':len(report),'changed':sum(r['action']=='sync' for r in report)},ensure_ascii=False))
